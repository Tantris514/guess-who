def build_sea():
    m = fresh_material("M_GW_Sea")
    usage(m, nanite=False)
    m.set_editor_property("tangent_space_normal", False)
    pos = expr(m, unreal.MaterialExpressionWorldPosition, -1400, 0)
    t = expr(m, unreal.MaterialExpressionTime, -1400, 100)
    amp = scalar(m, "SwellAmp", 110.0, -1400, 200)
    wpo = custom(m, SEA_WPO, ["P", "T", "Amp"], -900, -200, F3, "Sea swell")
    wire(wpo, ((pos, "P"), (t, "T"), (amp, "Amp")))
    mel.connect_material_property(wpo, "", MP.MP_WORLD_POSITION_OFFSET)
    ntex = tex_param(m, "NTex", -1400, 300, T("T_GW_SeaNormal"), ST.SAMPLERTYPE_NORMAL)
    nrm = custom(m, SEA_NORMAL, ["NTex", "P", "T", "Amp", "Detail"], -900, 100, F3, "Sea normal")
    wire(nrm, ((ntex, "NTex"), (pos, "P"), (t, "T"), (amp, "Amp"), (scalar(m, "Detail", 0.55, -1400, 400), "Detail")))
    mel.connect_material_property(nrm, "", MP.MP_NORMAL)
    ftex = tex_param(m, "FTex", -1400, 500, T("T_GW_SeaFoam"), ST.SAMPLERTYPE_GRAYSCALE)
    col = custom(m, SEA_COLOR, ["FTex", "P", "T", "FoamAmount", "Water", "FoamColor"], -900, 400, F4, "Sea colour")
    wire(col, ((ftex, "FTex"), (pos, "P"), (t, "T"), (scalar(m, "FoamAmount", 1.6, -1400, 600), "FoamAmount"),
               (vector(m, "Water", (0.005, 0.010, 0.014), -1400, 700), "Water"),
               (vector(m, "FoamColor", (0.40, 0.44, 0.46), -1400, 800), "FoamColor")))
    rgb = mask(m, col, -600, 400, r=True, g=True, b=True)
    foam = mask(m, col, -600, 500, a=True)
    mel.connect_material_property(rgb, "", MP.MP_BASE_COLOR)
    rough = expr(m, unreal.MaterialExpressionLinearInterpolate, -400, 500)
    mel.connect_material_expressions(scalar(m, "WaterRoughness", 0.07, -600, 600), "", rough, "A")
    mel.connect_material_expressions(scalar(m, "FoamRoughness", 0.6, -600, 680), "", rough, "B")
    mel.connect_material_expressions(foam, "", rough, "Alpha")
    mel.connect_material_property(rough, "", MP.MP_ROUGHNESS)
    mel.connect_material_property(scalar(m, "Specular", 0.5, -400, 700), "", MP.MP_SPECULAR)
    glow = expr(m, unreal.MaterialExpressionMultiply, -400, 800)
    mel.connect_material_expressions(rgb, "", glow, "A")
    mel.connect_material_expressions(scalar(m, "FoamGlow", 0.006, -600, 800), "", glow, "B")
    mel.connect_material_property(glow, "", MP.MP_EMISSIVE_COLOR)
    finish(m)



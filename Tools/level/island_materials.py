"""(in editor) Storm-island exterior: textures, MPC and master materials + instances.

  level/run.sh level/island_materials.py [tex] [mats]      (no args = both)

Textures come from Tools/level/island_src/tex (generated by island_src/gen/build_all.py) and go to
/Game/GW/Textures/Island. Normal maps were authored OpenGL-style (green up): they are imported as plain
TC_Normalmap and the HLSL below flips green itself.
Masters (/Game/GW/Materials/Master) and instances (/Game/GW/Environment):
  M_GW_Sea          animated storm sea: Gerstner swells (WPO), panning detail normals, whitecaps on the crests
  M_GW_Island       cliffs (triplanar wet rock), windswept grass on the plateau top, gravel terrace around the house
  M_GW_RainCurtain  additive unlit rain streaks for planes outside the windows (brighter with lightning)
  M_GW_RainGlass    thin-translucent window glass with rain drops (running on panes, static on the roof)
  M_GW_FoliageWind  wind-bent shrubs / tree crowns / bark swaying in the storm (WPO)
  MPC_GW_Storm      Flash (0..1, written by BP_GW_Storm at runtime), Wind
HLSL is checked offline with: python -I -X utf8 Tools/level/hlsl_check.py Tools/level/island_materials.py
"""

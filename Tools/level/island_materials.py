def import_textures():
    eal.make_directory(TEXD)
    TC = unreal.TextureCompressionSettings
    tasks = []
    for name in TEXTURES:
        t = unreal.AssetImportTask()
        t.filename = os.path.join(SRC, name + ".png")
        t.destination_path = TEXD
        t.destination_name = name
        t.automated = True
        t.replace_existing = True
        t.save = False
        tasks.append(t)
    tools.import_asset_tasks(tasks)
    for name, kind in TEXTURES.items():
        tex = unreal.load_asset(f"{TEXD}/{name}")
        if tex is None:
            print("  !! texture not imported", name)
            continue
        if kind == "normal":
            tex.set_editor_property("compression_settings", TC.TC_NORMALMAP)
            tex.set_editor_property("srgb", False)
            tex.set_editor_property("flip_green_channel", False)
        elif kind == "mask":
            tex.set_editor_property("compression_settings", TC.TC_GRAYSCALE)
            tex.set_editor_property("srgb", False)
        else:
            tex.set_editor_property("compression_settings", TC.TC_DEFAULT)
            tex.set_editor_property("srgb", True)
        eal.save_loaded_asset(tex)
    print(f"  island textures: {len(TEXTURES)}")


def T(name):
    return f"{TEXD}/{name}"


# ------------------------------------------------------------------ helpers (same conventions as Tools/ue_materials.py)
def fresh_material(name):
    path = f"{MASTER}/{name}"
    if eal.does_asset_exist(path):
        m = unreal.load_asset(path)
        mel.delete_all_material_expressions(m)
        for e in list(mel.get_material_expressions(m) or []):
            mel.delete_material_expression(m, e)
        return m
    return tools.create_asset(name, MASTER, unreal.Material, unreal.MaterialFactoryNew())


def expr(mat, cls, x, y, **props):
    e = mel.create_material_expression(mat, cls, x, y)
    for k, v in props.items():
        e.set_editor_property(k, v)
    return e


def tex_param(mat, name, x, y, tex, sampler):
    return expr(mat, unreal.MaterialExpressionTextureObjectParameter, x, y, parameter_name=name,
                texture=unreal.load_asset(tex), sampler_type=sampler)


def scalar(mat, name, value, x, y):
    return expr(mat, unreal.MaterialExpressionScalarParameter, x, y, parameter_name=name, default_value=value)


def vector(mat, name, rgb, x, y):
    return expr(mat, unreal.MaterialExpressionVectorParameter, x, y, parameter_name=name,
                default_value=unreal.LinearColor(rgb[0], rgb[1], rgb[2], 1.0))


def custom(mat, code, inputs, x, y, out=F3, desc="Custom"):
    e = expr(mat, unreal.MaterialExpressionCustom, x, y, code=code, output_type=out, description=desc)
    ins = []
    for n in inputs:
        ci = unreal.CustomInput()
        ci.set_editor_property("input_name", n)
        ins.append(ci)
    e.set_editor_property("inputs", ins)
    return e


def wire(c, pairs):
    for src, pin in pairs:
        if not mel.connect_material_expressions(src, "", c, pin):
            raise RuntimeError(f"could not wire {pin}")


def mask(mat, src, x, y, r=False, g=False, b=False, a=False):
    e = expr(mat, unreal.MaterialExpressionComponentMask, x, y, r=r, g=g, b=b, a=a)
    mel.connect_material_expressions(src, "", e, "")
    return e


def mpc_param(mat, name, x, y):
    return expr(mat, unreal.MaterialExpressionCollectionParameter, x, y, collection=unreal.load_asset(MPC_PATH),
                parameter_name=name)


def usage(mat, nanite=True):
    for flag in ("used_with_instanced_static_meshes", "used_with_static_lighting"):
        try:
            mat.set_editor_property(flag, True)
        except Exception:
            pass
    if nanite:
        mat.set_editor_property("used_with_nanite", True)


def finish(mat):
    mel.layout_material_expressions(mat)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat)


def instance(name, parent, scalars=None, vectors=None):
    path = f"{ENV}/{name}"
    mi = unreal.load_asset(path) if eal.does_asset_exist(path) else tools.create_asset(
        name, ENV, unreal.MaterialInstanceConstant, unreal.MaterialInstanceConstantFactoryNew())
    mel.set_material_instance_parent(mi, unreal.load_asset(f"{MASTER}/{parent}"))
    for k, v in (scalars or {}).items():
        mel.set_material_instance_scalar_parameter_value(mi, k, v)
    for k, v in (vectors or {}).items():
        mel.set_material_instance_vector_parameter_value(mi, k, unreal.LinearColor(v[0], v[1], v[2], 1.0))
    mel.update_material_instance(mi)
    eal.save_loaded_asset(mi)
    return mi


def ensure_mpc():
    eal.make_directory(ENV)
    mpc = unreal.load_asset(MPC_PATH) if eal.does_asset_exist(MPC_PATH) else tools.create_asset(
        "MPC_GW_Storm", ENV, unreal.MaterialParameterCollection, unreal.MaterialParameterCollectionFactoryNew())
    have = {str(p.get_editor_property("parameter_name")) for p in mpc.get_editor_property("scalar_parameters")}
    params = list(mpc.get_editor_property("scalar_parameters"))
    for name, val in (("Flash", 0.0), ("Wind", 1.0), ("BoltAz", 0.0), ("BoltSeed", 0.0)):
        if name not in have:
            p = unreal.CollectionScalarParameter()
            p.set_editor_property("parameter_name", name)
            p.set_editor_property("default_value", val)
            params.append(p)
    mpc.set_editor_property("scalar_parameters", params)
    eal.save_loaded_asset(mpc)
    return mpc


